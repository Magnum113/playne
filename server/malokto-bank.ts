const PACK_COUNT = 30;
const logicQuestions = Array.from({ length: PACK_COUNT }, (_, index) => {
  const parameter = Math.floor(index / 5);
  const digitSum = 4 + parameter;
  const divisor = 3 + parameter;
  const remainder = 1 + parameter % 2;
  const ending = 2 + parameter;
  const varieties = [
    {
      prompt: `Назови двузначное число, сумма цифр которого равна ${digitSum}`,
      accepts: (n: number) => n < 100 && Math.floor(n / 10) + n % 10 === digitSum,
    },
    {
      prompt: `Назови двузначное число, которое при делении на ${divisor} даёт остаток ${remainder}`,
      accepts: (n: number) => n < 100 && n % divisor === remainder,
    },
    {
      prompt: `Назови двузначное число, кратное ${5 + parameter}`,
      accepts: (n: number) => n < 100 && n % (5 + parameter) === 0,
    },
    {
      prompt: `Назови трёхзначное число, которое одинаково читается в обе стороны и заканчивается на ${ending}`,
      accepts: (n: number) => Math.floor(n / 100) === ending && n % 10 === ending,
    },
    {
      prompt: `Назови двузначное число, в котором десятков ровно на ${parameter + 1} больше, чем единиц`,
      accepts: (n: number) => n < 100 && Math.floor(n / 10) - n % 10 === parameter + 1,
    },
  ];
  const { prompt, accepts } = varieties[index % varieties.length];
  const answers = Array.from({ length: 990 }, (_, i) => i + 10).filter(accepts);
  // Round numbers are usually easier to reach for.
  answers.sort((left, right) => Number(right % 10 === 0) - Number(left % 10 === 0) || left - right);
  const band = (tier: number) => answers.filter((_, rank) =>
    Math.floor(rank * 4 / answers.length) === tier,
  ).join(", ");
  return `${prompt}|${[0, 1, 2, 3].map(band).join("|")}`;
});
sections.push({ category: "Числа", questions: logicQuestions });

const POINTS = [25, 45, 70, 100];
export const MALOKTO_PACKS: RareQuestion[][] = Array.from({ length: PACK_COUNT }, (_, dayIndex) =>
  sections.map(({ category, questions }, sectionIndex) => {
    const [prompt, ...bands] = questions[dayIndex].split("|");
    const populated = bands.filter(Boolean);
    // For short, closed lists distribute all concepts from familiar to unusual.
    const scores = populated.length === 1 ? [70] : populated.length === 2 ? [45, 100] : populated.length === 3 ? [25, 70, 100] : POINTS;
    const answers = populated.flatMap((band, tier) => band.split(",").map(entry => {
      const [name, ...aliases] = entry.split("/").map(item => item.trim());
      return { name, aliases: [...new Set(aliases)], score: scores[tier] };
    }));
    return { id: `mk-${dayIndex + 1}-${sectionIndex + 1}`, category, prompt, answers };
  }),
);

export function maloktoPack(day: string, firstDay: string): RareQuestion[] | undefined {
  const index = (Date.parse(day) - Date.parse(firstDay)) / DAY_MS;
  if (!Number.isInteger(index) || index < 0) return;
  const content = MALOKTO_PACKS[index];
  if (content?.length !== MALOKTO_ROUNDS) return;
  // Rotate the order of topics to keep the first question varied.
  const offset = index % MALOKTO_ROUNDS;
  return [...content.slice(offset), ...content.slice(0, offset)];
}

export function normalizeRareAnswer(value: string) {
  const normalized = value.normalize("NFKC").toLowerCase().trim();
  if ([...normalized].length === 1) return normalized;
  return normalized.replaceAll("ё", "е").replace(/[’'ʼ.]/g, "")
    .replace(/[\s\p{Pd}]+/gu, " ").trim();
}

export function evaluateMalokto(
  task: RareQuestion | undefined, startedAt: number, input: unknown, now: number,
): MaloktoAnswer {
  if (!task || !Number.isFinite(startedAt)) throw Error("Сначала открой вопрос");
  if (now < startedAt) throw Error("Дождись начала отсчёта");
  const elapsedMs = now - startedAt;
  if (elapsedMs >= MALOKTO_ROUND_MS) return { name: null, score: 0, elapsedMs: MALOKTO_ROUND_MS };
  if (typeof input !== "string" || !input.trim() || input.length > 100) throw Error("Введи один ответ");
  const normalized = normalizeRareAnswer(input);
  const match = task.answers.find(({ name, aliases }) =>
    [name, ...aliases].some(alias => normalizeRareAnswer(alias) === normalized),
  );
  if (!match) throw Error("Такого ответа пока нет в списке. Попробуй другой.");
  return { name: match.name, score: match.score, elapsedMs };
}
